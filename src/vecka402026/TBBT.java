package vecka402026;

public class TBBT {
    public void catchPhrases (String person) {
        switch (person) {
            case "Sheldon":
                System.out.println("Knock, Knock, Knock, Penny!");
                break;
            case "Mom":
                System.out.println("My mother got me tested.");
                break;
            case "Lenard":
                System.out.println("Our children will be smart and beautiful!");
                break;
            default:
                System.out.println("Are you serious? Choose a right character.");
        }
    }
}
